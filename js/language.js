document.addEventListener('DOMContentLoaded', () => {
    const langToggle = document.getElementById('langToggle');

    const applyLanguage = (lang) => {
        const elements = document.querySelectorAll('[data-translate]');

        elements.forEach(el => {
            const key = el.getAttribute('data-translate');
            if (lang === 'en' && dictionary.en[key]) {
                // Simpan text asli Indonesia di dataset jika belum ada
                if (!el.dataset.originalText) el.dataset.originalText = el.innerText;
                el.innerText = dictionary.en[key];
            } else if (lang === 'id' && el.dataset.originalText) {
                // Kembalikan ke teks asli Indonesia
                el.innerText = el.dataset.originalText;
            }
        });

        // Update teks visual tombol indikator bahasa
        langToggle.innerText = lang === 'id' ? 'EN' : 'ID';
        langToggle.setAttribute('aria-label', lang === 'id' ? 'Switch to English' : 'Ubah ke Bahasa Indonesia');
    };

    // Inisialisasi status bahasa berdasarkan memori penyimpanan lokal browser
    if (AppState.currentLanguage === 'en') {
        applyLanguage('en');
    }

    // Event Listener Aksi Klik Tombol Ganti Bahasa
    langToggle.addEventListener('click', () => {
        AppState.currentLanguage = AppState.currentLanguage === 'id' ? 'en' : 'id';
        localStorage.setItem('faadhil_digital_lang', AppState.currentLanguage);
        applyLanguage(AppState.currentLanguage);
    });
});